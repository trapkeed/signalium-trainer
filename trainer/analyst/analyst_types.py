# Role → permissions mapping
ROLE_PERMISSIONS: dict = {
    Role.ADMIN: {p for p in Permission},
    Role.RESEARCHER: {Permission.READ, Permission.SUMMARIZE, Permission.COMPARE},
    Role.VIEWER: {Permission.READ},
}


def has_permission(role: Role, permission: Permission) -> bool:
    return permission in ROLE_PERMISSIONS.get(role, set())


# Safety guardrails — responses containing these are rejected
PROHIBITED_PATTERNS = [
    "BUY",
    "SELL",
    "LONG",
    "SHORT",
    "ENTER TRADE",
    "EXIT TRADE",
    "PLACE ORDER",
    "EXECUTE ORDER",
]


def is_safe_response(text: str) -> bool:
    """Return False if the response contains prohibited trading signals."""
    upper = text.upper()
    return not any(p in upper for p in PROHIBITED_PATTERNS)
